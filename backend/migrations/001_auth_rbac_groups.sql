-- CampusCare final schema upgrade.
-- Preserves the existing MVP complaint rows and adds auth, sessions, audit, and groups.
CREATE TABLE IF NOT EXISTS public."user" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(254) NOT NULL,
  full_name varchar(100) NOT NULL,
  password_hash text NOT NULL,
  role varchar(10) NOT NULL DEFAULT 'user',
  is_banned boolean NOT NULL DEFAULT false,
  token_version integer NOT NULL DEFAULT 0,
  ban_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_user_email ON public."user"(email);
CREATE INDEX IF NOT EXISTS ix_user_role ON public."user"(role);
CREATE INDEX IF NOT EXISTS ix_user_is_banned ON public."user"(is_banned);
CREATE INDEX IF NOT EXISTS ix_user_created_at ON public."user"(created_at);

ALTER TABLE public.complaint
  ADD COLUMN IF NOT EXISTS owner_id integer REFERENCES public."user"(id);
CREATE INDEX IF NOT EXISTS ix_complaint_owner_id ON public.complaint(owner_id);

CREATE TABLE IF NOT EXISTS public.refreshsession (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public."user"(id),
  token_hash text NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  ip_address text,
  user_agent text
);
CREATE INDEX IF NOT EXISTS ix_refreshsession_user_id ON public.refreshsession(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS ix_refreshsession_token_hash ON public.refreshsession(token_hash);
CREATE INDEX IF NOT EXISTS ix_refreshsession_expires_at ON public.refreshsession(expires_at);

CREATE TABLE IF NOT EXISTS public.auditevent (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer,
  event varchar(60) NOT NULL,
  target_type text,
  target_id text,
  detail text,
  ip_address text,
  user_agent text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_auditevent_user_id ON public.auditevent(user_id);
CREATE INDEX IF NOT EXISTS ix_auditevent_event ON public.auditevent(event);
CREATE INDEX IF NOT EXISTS ix_auditevent_created_at ON public.auditevent(created_at);

CREATE TABLE IF NOT EXISTS public.loginattempt (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_key text NOT NULL,
  ip_address text NOT NULL,
  succeeded boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_loginattempt_email_key ON public.loginattempt(email_key);
CREATE INDEX IF NOT EXISTS ix_loginattempt_ip_address ON public.loginattempt(ip_address);
CREATE INDEX IF NOT EXISTS ix_loginattempt_created_at ON public.loginattempt(created_at);

CREATE TABLE IF NOT EXISTS public."group" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  owner_id integer NOT NULL REFERENCES public."user"(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_group_name ON public."group"(name);
CREATE INDEX IF NOT EXISTS ix_group_owner_id ON public."group"(owner_id);

CREATE TABLE IF NOT EXISTS public.groupmember (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id integer NOT NULL REFERENCES public."group"(id),
  user_id integer NOT NULL REFERENCES public."user"(id),
  can_create boolean NOT NULL DEFAULT false,
  can_edit boolean NOT NULL DEFAULT false,
  can_assign boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_groupmember_group_id ON public.groupmember(group_id);
CREATE INDEX IF NOT EXISTS ix_groupmember_user_id ON public.groupmember(user_id);

CREATE TABLE IF NOT EXISTS public.grouprecord (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id integer NOT NULL REFERENCES public."group"(id),
  created_by integer NOT NULL REFERENCES public."user"(id),
  title varchar(120) NOT NULL,
  body varchar(2000) NOT NULL,
  assignee_id integer REFERENCES public."user"(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_grouprecord_group_id ON public.grouprecord(group_id);

-- These tables are accessed through the FastAPI server using its database connection.
-- No direct anon/authenticated PostgREST policies are defined; enable RLS to prevent public-key access.
ALTER TABLE public."user" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.refreshsession ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auditevent ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.loginattempt ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."group" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.groupmember ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.grouprecord ENABLE ROW LEVEL SECURITY;
